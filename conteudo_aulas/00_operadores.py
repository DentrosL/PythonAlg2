# + -> soma
print(2 + 3) # r: 5

# - -> subtração
print(5 - 2) # r: 3

# * -> multiplicação
print(2 * 3) # r: 6

# / -> divisão
print(6 / 2) # r: 3.0

# // -> divisão inteira
print(7 // 2) # r: 3

# % -> resto da divisão
print(7 % 2) # r: 1

# ** -> potência
print(2 ** 3) # r: 8

# == -> igual
print(2 == 2) # r: True

# != -> diferente
print(2 != 3) # r: True

# > -> maior
print(5 > 2) # r: True

# < -> menor
print(2 < 5) # r: True

# >= -> maior ou igual
print(5 >= 5) # r: True

# <= -> menor ou igual
print(4 <= 5) # r: True

# and -> E
print(True and True) # r: True

# or -> OU
print(True or False) # r: True

# not -> NÃO
print(not True) # r: False

# = -> atribuição
x = 5
print(x) # r: 5

# += -> soma e atribui
x = 5
x += 2
print(x) # r: 7

# -= -> subtrai e atribui
x = 5
x -= 2
print(x) # r: 3

# *= -> multiplica e atribui
x = 5
x *= 2
print(x) # r: 10

# /= -> divide e atribui
x = 10
x /= 2
print(x) # r: 5.0

# //= -> divisão inteira e atribui
x = 7
x //= 2
print(x) # r: 3

# %= -> resto e atribui
x = 7
x %= 2
print(x) # r: 1

# **= -> potência e atribui
x = 2
x **= 3
print(x) # r: 8

# is -> verifica se é o mesmo objeto
x = None
print(x is None) # r: True

# is not -> verifica se não é o mesmo objeto
x = None
print(x is not None) # r: False

# in -> verifica se está dentro
print(2 in [1, 2, 3]) # r: True

# not in -> verifica se não está dentro
print(5 not in [1, 2, 3]) # r: True